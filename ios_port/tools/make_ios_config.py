#!/usr/bin/env python3
"""Generate ds2_ios.toml from the v121 Switch config, tuned for iPhone 11 / A13.

Keeps the upstream file's comments intact, overrides only the keys that matter
on iOS, appends iOS-only knobs, and validates the result with tomllib.
"""
import argparse
import pathlib
import re
import sys
import tomllib

# value, reason
OVERRIDES = {
    "log_level": ('"warn"', "less log IO on flash"),
    "user_language": ("12", "Russian only"),
    "user_game_region": ("766", "Europe SKU (Russian)"),
    "ds2_switch_cpu_mhz": ("0", "no Horizon clock sysmodule"),
    "ds2_switch_gpu_mhz": ("0", "no Horizon clock sysmodule"),
    "ds2_switch_mem_mhz": ("0", "no Horizon clock sysmodule"),
    "ds2_mesa_env": ('""', "no Mesa NVK / nouveau on iOS"),
    "ds2_switch_nvmap_mb": ("0", "no /dev/nvmap"),
    "ds2_switch_saltynx": ("false", "no SaltyNX sysmodule"),
    "ds2_switch_stack_sampling": ("false", "no Switch profiler"),
    "ds2_switch_commit_granule_kb": ("0", "no Horizon guest-memory granule"),
    "ds2_watchdog_probe_tables": ("0", "diagnostics off"),
    "ds2_export_stats": ("false", "no periodic stats writes"),
    "ds2_func_counts": ("false", "no per-function counters"),
    "ds2_editor_wait_log": ("false", "editor disabled"),
    "ds2_editor_force_free_s": ("0", "editor disabled"),
    "ds2_editor_open_mode": ("0", "editor disabled"),
    "ds2_editor_open_after_s": ("0", "editor disabled"),
    "ds2_native_gpu_profile": ("false", "no GPU profiler"),
    "ds2_native_gpu_profile_every": ("0", "no GPU profiler"),
    "ds2_native_log_every": ("0", "no per-frame native log"),
    "ds2_native_capture_combo": ("false", "no L3+R3 capture"),
    "ds2_native_capture_resolves": ("false", "no frame dumps"),
    "ds2_native_shader_profile_every": ("0", "no shader group timing"),
    "ds2_native_probe": ("0", "diagnostic probe off"),
    "ds2_native_msaa_host": ("false", "save MSAA bandwidth/RAM on A13"),
    "ds2_native_halfres_divisor": ("2", "keep half-res bonfire fog (big GPU win)"),
    "ds2_native_fold_texture_signs": ("true", "specialization constants remove fetch branches"),
    "ds2_shader_library": ('"ds2_shaders.spvlib"', "loader swaps in the .spvz sibling"),
    "ds2_shader_library_index": ("true", "required for compressed pack"),
    "ds2_shader_cache": ('""', "do not grow a second cache on device"),
}

# Keys that exist in the SDK but not in the shipped Switch config.
NEW_KEYS = [
    ("ds2_render_scale", "0.75", "540p from the 720p base; biggest FPS lever on A13"),
    ("ds2_fps_cap", "30", "stable 30 fps, less thermal throttling than 60"),
    ("ds2_fps_lock_vsync", "true", "present on CADisplayLink"),
    ("ds2_sharpen", "true", "compensate the 0.75 upscale"),
    ("ds2_sharpness", "0.45", "mild sharpening, avoid halos"),
    ("ds2_resolution_prompt", "false", "skip start screen; language fixed to Russian"),
]

LINE = re.compile(r"^(\s*)([a-z0-9_]+)(\s*=)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", help="original ds2.toml from the v121 release")
    ap.add_argument("dst", help="output ds2_ios.toml")
    a = ap.parse_args()

    lines = pathlib.Path(a.src).read_text(encoding="utf-8").splitlines()
    seen = set()
    out = []
    for ln in lines:
        m = LINE.match(ln)
        if not m:
            out.append(ln)
            continue
        key = m.group(2)
        if key in OVERRIDES and key not in seen:
            value, why = OVERRIDES[key]
            out.append(f"{key} = {value}  # iOS: {why}")
            seen.add(key)
        else:
            out.append(ln)

    missing = set(OVERRIDES) - seen
    out += ["", "# ---- iOS / iPhone 11 (A13, 4 GB) ----------------------------------",
            "# Generated by ios_port/tools/make_ios_config.py. Values below are SDK",
            "# cvars that the Switch release does not set explicitly."]
    for key, value, why in NEW_KEYS:
        out.append(f"{key} = {value}  # {why}")
    if missing:
        out.append(f"# NOTE: not present in source config, left at SDK defaults: {', '.join(sorted(missing))}")

    text = "\n".join(out) + "\n"
    pathlib.Path(a.dst).write_text(text, encoding="utf-8")
    parsed = tomllib.loads(text)
    print(f"written  : {a.dst}")
    print(f"parsed   : {len(parsed)} keys, TOML valid")
    print(f"overridden: {len(seen)}  | appended: {len(NEW_KEYS)} | absent in source: {len(missing)}")
    for k in ("user_language", "ds2_render_scale", "ds2_fps_cap", "ds2_shader_library",
              "ds2_switch_cpu_mhz", "ds2_native_msaa_host"):
        print(f"  {k:28s} = {parsed.get(k, '<SDK default>')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
